// Appearance (Figma "Dark mode · key screens", PRF-01g): Light is the default, Dark is a
// per-phone choice made on Profile. The choice lives in this phone's localStorage and nothing is
// sent to the server (the switch's own line says "on this phone only"). No DOM here, so tests
// can import it; the DOM side is themeStore.ts.

export type Theme = "light" | "dark";

export const THEME_STORAGE_KEY = "cf-theme";

/** The browser's address-bar / status-bar colour: Figma color/bg/default in each mode. */
export const THEME_COLOR: Record<Theme, string> = {
  light: "#ffffff",
  dark: "#0b141b",
};

/** The two methods of Storage this module uses. */
export interface ThemeStorage {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
}

/** Anything but "dark" (missing, old, edited by hand) reads as Light, the default. */
export function parseTheme(raw: unknown): Theme {
  return raw === "dark" ? "dark" : "light";
}

/** The saved choice. Storage can be missing or throw (private window, blocked site data): Light then. */
export function readTheme(storage: ThemeStorage | null): Theme {
  try {
    return parseTheme(storage?.getItem(THEME_STORAGE_KEY));
  } catch {
    return "light";
  }
}

/** Remembers the choice; false when the phone wouldn't keep it (the choice still holds until the page closes). */
export function writeTheme(storage: ThemeStorage | null, theme: Theme): boolean {
  try {
    if (storage === null) return false;
    storage.setItem(THEME_STORAGE_KEY, theme);
    return true;
  } catch {
    return false;
  }
}

const LIGHT_ICONS = "/icons/";
const DARK_ICONS = "/icons/dark/";

/**
 * Icons are SVG files with their colours drawn in, and an <img> can't take a CSS colour, so each
 * has a Dark twin under /icons/dark/ (generated by scripts/make-dark-icons.mjs from the Figma Dark
 * values). Paths outside /icons/ are returned as they are.
 */
export function iconSrc(path: string, theme: Theme): string {
  if (theme !== "dark" || !path.startsWith(LIGHT_ICONS) || path.startsWith(DARK_ICONS)) return path;
  return DARK_ICONS + path.slice(LIGHT_ICONS.length);
}

